"""Regenerate INDEX.md and _index/ from the vault contents (spec section 8)."""
from __future__ import annotations

from pathlib import Path

import vaultlib as v

HEADER_NOTE = "<!-- Generated by build_index.py. Do not edit; changes are overwritten. -->\n"


def _cell(text) -> str:
    return str(text if text is not None else "").replace("|", "\\|").replace("\n", " ").strip()


def _sources_cell(e: v.Entity) -> str:
    parts = []
    for s in v.as_list(e.fm.get("sources")):
        if isinstance(s, dict):
            pages = s.get("pages") or []
            if pages:
                shown = ", ".join(str(p) for p in pages[:4]) + ("…" if len(pages) > 4 else "")
                parts.append(f"{s.get('source')} p.{shown}")
            else:
                parts.append(str(s.get("source")))
    if e.layer == "ideas":
        return f"idea ({e.fm.get('status', 'draft')})"
    return "; ".join(parts)


def backlinks(vault: v.Vault) -> dict[str, list[str]]:
    back: dict[str, set[str]] = {}
    for e in vault.entities:
        targets = {t for _, t in e.refs()} | set(v.wikilinks_in(e.body))
        for t in targets:
            if t != e.id:
                back.setdefault(t, set()).add(e.id)
    for n in vault.notes:
        if n.fm.get("about"):
            back.setdefault(n.fm["about"], set()).add(f"table/notes/{n.path.stem}")
    for s in vault.sessions:
        for t in v.as_list(s.fm.get("present")) + v.as_list(s.fm.get("changed")):
            back.setdefault(t, set()).add(f"table/sessions/{s.path.stem}")
    return {k: sorted(vs) for k, vs in sorted(back.items())}


def build(root: Path) -> list[Path]:
    vault = v.load_vault(root)
    out_dir = vault.root / "_index"
    out_dir.mkdir(exist_ok=True)
    written = []

    for old in out_dir.glob("*.md"):
        old.unlink()

    counts: dict[str, dict[str, int]] = {t: {"canon": 0, "ideas": 0} for t in v.TYPES}
    notes_about = {n.fm.get("about") for n in vault.notes}
    for t in v.TYPES:
        ents = sorted((e for e in vault.entities if e.type == t),
                      key=lambda e: (e.layer != "canon", v.norm_name(e.name)))
        for e in ents:
            if e.layer in counts[t]:
                counts[t][e.layer] += 1
        lines = [HEADER_NOTE, f"# {t} ({len(ents)})\n",
                 "| ID | Name | Layer | Summary | Tags | Sources |",
                 "|---|---|---|---|---|---|"]
        for e in ents:
            name = e.name
            aliases = v.as_list(e.fm.get("aliases"))
            if aliases:
                name += f" (aka {', '.join(map(str, aliases))})"
            if e.id in notes_about:
                name += " ✎"
            lines.append("| " + " | ".join(_cell(x) for x in (
                e.id, name, e.layer, e.fm.get("summary", ""),
                ", ".join(map(str, v.as_list(e.fm.get("tags")))), _sources_cell(e))) + " |")
        p = out_dir / f"{t}.md"
        p.write_text("\n".join(lines) + "\n", encoding="utf-8")
        written.append(p)

    back = backlinks(vault)
    lines = [HEADER_NOTE, "# Backlinks\n", "Which entities, notes and sessions point at each entity.\n"]
    for target, srcs in back.items():
        lines.append(f"- **{target}** ← " + ", ".join(srcs))
    p = out_dir / "backlinks.md"
    p.write_text("\n".join(lines) + "\n", encoding="utf-8")
    written.append(p)

    # INDEX.md
    meta = vault.meta
    lines = [HEADER_NOTE, f"# {meta.get('name', 'Vault')}\n"]
    systems = ", ".join(map(str, v.as_list(meta.get("systems")))) or "unspecified"
    lines.append(f"Systems: {systems}. Format version {meta.get('format')}.\n")
    lines.append("Read order for what is true at this table: `table/` notes, then `canon/`, "
                 "then `ideas/` only where status is `used`.\n")
    lines.append("## Sources\n")
    if vault.sources:
        lines += ["| ID | Title | Kind | System | Pages |", "|---|---|---|---|---|"]
        for sid, s in sorted(vault.sources.items()):
            lines.append("| " + " | ".join(_cell(x) for x in (
                sid, s.get("title", ""), s.get("kind", ""), s.get("system", ""), s.get("pages", ""))) + " |")
        lines.append("\nChapter outlines are in `sources/<id>.md`.\n")
    else:
        lines.append("None yet.\n")
    lines.append("## Entities\n")
    lines += ["| Type | Canon | Ideas | Index |", "|---|---|---|---|"]
    for t in v.TYPES:
        c = counts[t]
        lines.append(f"| {t} | {c['canon']} | {c['ideas']} | [_index/{t}.md](_index/{t}.md) |")
    lines.append("\nReverse links: [_index/backlinks.md](_index/backlinks.md). "
                 "✎ in a type index means a table note overrides part of that entity.\n")
    lines.append("## Recent sessions\n")
    sessions = sorted(vault.sessions, key=lambda s: (str(s.fm.get("date", "")), s.fm.get("number") or 0),
                      reverse=True)[:5]
    if sessions:
        for s in sessions:
            title = s.fm.get("title") or ""
            lines.append(f"- [{s.fm.get('date')} · session {s.fm.get('number')}"
                         f"{' · ' + title if title else ''}](table/sessions/{s.path.name})")
    else:
        lines.append("None yet.")
    lines.append("\n## Table\n\n- [Party](table/party.md)\n- Notes on entities: `table/notes/`\n")
    p = vault.root / "INDEX.md"
    p.write_text("\n".join(lines) + "\n", encoding="utf-8")
    written.append(p)
    return written
