"""Bundle a vault into a few files for upload to a Claude Project (spec section 9)."""
from __future__ import annotations

import shutil
from pathlib import Path

import vaultlib as v
import build_index

TEMPLATES = Path(__file__).resolve().parent.parent / "templates"


def _entity_block(e: v.Entity) -> str:
    fm = {k: val for k, val in e.fm.items() if k not in ("id", "name")}
    head = f"# {e.id} — {e.name}\n\n"
    meta = v.dump_frontmatter(fm).strip().strip("-").strip()
    return head + "```yaml\n" + meta + "\n```\n\n" + e.body.strip() + "\n"


def _write_parts(out: Path, stem: str, title: str, blocks: list[str], max_bytes: int) -> list[Path]:
    parts: list[list[str]] = [[]]
    size = 0
    for b in blocks:
        n = len(b.encode("utf-8"))
        if parts[-1] and size + n > max_bytes:
            parts.append([])
            size = 0
        parts[-1].append(b)
        size += n
    written = []
    for k, blks in enumerate(parts, 1):
        suffix = f"-part{k}" if len(parts) > 1 else ""
        p = out / f"{stem}{suffix}.md"
        label = f" (part {k} of {len(parts)})" if len(parts) > 1 else ""
        p.write_text(f"<!-- {title}{label}. Generated by lorekeeper digest. -->\n\n" + "\n---\n\n".join(blks),
                     encoding="utf-8")
        written.append(p)
    return written


def build(root: Path, out: Path, max_kb: int = 300) -> dict:
    root = Path(root)
    build_index.build(root)
    vault = v.load_vault(root)
    out = Path(out)
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    max_bytes = max_kb * 1024
    files: list[Path] = []

    idx_parts = [(root / "INDEX.md").read_text(encoding="utf-8")]
    for t in v.TYPES:
        idx_parts.append((root / "_index" / f"{t}.md").read_text(encoding="utf-8"))
    idx_parts.append((root / "_index" / "backlinks.md").read_text(encoding="utf-8"))
    p = out / "00-index.md"
    p.write_text("\n\n".join(idx_parts), encoding="utf-8")
    files.append(p)

    src_blocks = []
    for sid, s in sorted(vault.sources.items()):
        fm = {k: val for k, val in s.items() if not k.startswith("_")}
        src_blocks.append(f"# source: {sid} — {s.get('title', '')}\n\n```yaml\n"
                          + v.dump_frontmatter(fm).strip().strip("-").strip() + "\n```\n\n" + s["_body"].strip() + "\n")
    if src_blocks:
        files += _write_parts(out, "01-sources", "Source outlines", src_blocks, max_bytes)

    for t in v.TYPES:
        ents = sorted((e for e in vault.entities if e.layer == "canon" and e.type == t), key=lambda e: e.id)
        if ents:
            files += _write_parts(out, f"canon-{t}", f"Canon {t} entities", [_entity_block(e) for e in ents],
                                  max_bytes)
    ideas = sorted((e for e in vault.entities if e.layer == "ideas"), key=lambda e: e.id)
    if ideas:
        files += _write_parts(out, "ideas", "Generated ideas (not canon)", [_entity_block(e) for e in ideas],
                              max_bytes)

    table_blocks = []
    party = root / "table" / "party.md"
    if party.exists():
        table_blocks.append("# table/party\n\n" + party.read_text(encoding="utf-8"))
    for n in vault.notes:
        table_blocks.append(f"# table/notes/{n.path.stem} (about {n.fm.get('about')})\n\n" + n.body.strip() + "\n")
    for s in sorted(vault.sessions, key=lambda s: (str(s.fm.get("date")), s.fm.get("number") or 0)):
        table_blocks.append(f"# table/sessions/{s.path.stem}\n\n```yaml\n"
                            + v.dump_frontmatter(s.fm).strip().strip("-").strip() + "\n```\n\n" + s.body.strip() + "\n")
    files += _write_parts(out, "table", "Table layer: what happened at this table. Re-upload after each session",
                          table_blocks or ["No sessions yet."], max_bytes)

    instructions = TEMPLATES / "project-instructions.md"
    if instructions.exists():
        shutil.copy(instructions, out / "PROJECT-INSTRUCTIONS.md")

    return {
        "out": str(out),
        "files": [{"file": f.name, "kb": round(f.stat().st_size / 1024, 1)} for f in files],
        "total_kb": round(sum(f.stat().st_size for f in files) / 1024, 1),
        "instructions": str(out / "PROJECT-INSTRUCTIONS.md") if instructions.exists() else None,
    }
